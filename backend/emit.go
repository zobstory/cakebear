// rtPkg is the import alias for cakebear's runtime inside generated code.
// Deliberately unlovely: it shares a namespace with mangled user identifiers,
// and a user variable called `rt` should not be able to shadow it.
const rtPkg = "cakebearrt"

// emitter builds Go source from the IR.
//
// Source text is written directly rather than assembled as a go/ast tree and
// printed. The emitter runs on every build, the output is immediately handed to
// a real Go parser that will reject anything malformed, and a tree buys nothing
// here but allocations.
type emitter struct {
	buf strings.Builder
	// usesRuntime records whether anything actually called into the runtime.
	// An unused import is a compile error in Go, so this decides whether the
	// import gets written at all.
	usesRuntime bool
	// depth is the indentation of the statement being emitted, so a function
	// literal inside one of its expressions can indent its body to match.
	depth int
	// unsupported collects IR this backend cannot emit yet. Build refuses the
	// module before go build ever sees the placeholder written for each.
	unsupported []Unsupported
	// needsRun records a call into node:http, a timer, or async code. Such a
	// program ends main with the runtime's Run, which drives the main domain:
	// its promise reactions, its timers, and a listening server.
	needsRun bool
	// usesDomain records a reference to the current domain (dom), so main
	// declares its own only when its body uses it.
	usesDomain bool
	// asyncVoid is set while emitting the body of an async function whose
	// promise holds nothing, where a bare return returns struct{}{}.
	asyncVoid bool
	// hoisted holds the top-level variables declared at package level. Their
	// declarations in main become assignments.
	hoisted map[*ir.VarDecl]bool
	// prefixes holds each module's prefix for its top-level names, by file,
	// in a program of several modules, and cur the file of the module being
	// emitted (emit_program.go).
	prefixes map[string]string
	cur      string
	// order is set while emitting an expression whose reads must be ordered
	// against its calls, and usesRead once one was (order.go).
	order    bool
	usesRead bool
	// shapeUse holds where the program first uses each shape, and layouts
	// the key tables declared so far, by shape and key order (emit_object.go).
	shapeUse    map[*ir.Shape]ir.Span
	layouts     map[string]string
	layoutDecls []string
	// optionals holds the setters and deleters of optional fields the
	// program uses (emit_optional.go).
	optionals map[optionalOp]bool
	// held holds what the source calls the value of each Let in scope, by
	// the Let's name (emit_cond.go).
	held map[string]heldName
	// errorState is throw's and try's, and the site table's (emit_try.go).
	errorState
}

// Emit renders a program as the contents of a Go main package. IR the backend
// cannot emit yet appears as an #error line; Build reports it properly.
func Emit(p *ir.Program) string {
	src, _, err := emit(p)
	if err != nil {
		return "#error " + err.Error() + "\n"
	}
	return src
}

// emit renders p. An error is a program the backend refuses outright: one
// that breaks the IR's invariants, which is a bug in lowering, or one of
// several modules, which is M3's step 6.
func emit(p *ir.Program) (string, []Unsupported, error) {
	if err := p.Validate(); err != nil {
		return "", nil, fmt.Errorf("invalid IR, a bug in lowering: %w", err)
	}
	for i, m := range p.Modules {
		if m.Async && i != p.Entry {
			return "", nil, fmt.Errorf("%s has a top-level await, which only the entry module may have so far", m.File)
		}
	}
	var e emitter

	// The body is emitted first so usesRuntime is known before the header,
	// which is what decides whether the runtime import appears.
	body := e.program(p)

	var out strings.Builder
	out.WriteString("// Code generated by cakec. DO NOT EDIT.\n")
	out.WriteString("//\n")
	fmt.Fprintf(&out, "// Source: %s\n\n", p.EntryModule().Name)
	out.WriteString("package main\n\n")
	if e.usesRuntime {
		fmt.Fprintf(&out, "import %s %q\n\n", rtPkg, genModule+"/"+rtDir)
	}
	out.WriteString(body)
	return out.String(), sortedUnsupported(e.unsupported), nil
}

// capture runs an emit step against a fresh buffer and returns what it wrote,
// leaving e.usesRuntime accumulated across calls.
func (e *emitter) capture(emit func()) string {
	saved := e.buf
	e.buf = strings.Builder{}
	emit()
	written := e.buf.String()
	e.buf = saved
	return written
}

func (e *emitter) function(fn *ir.Func) {
	// Every function takes the domain it runs in first (emit_async.go).
	e.usesRuntime = true
	fmt.Fprintf(&e.buf, "func %s(%s", e.top(e.cur, fn.Name), domainParam)
	for _, p := range fn.Params {
		fmt.Fprintf(&e.buf, ", %s %s", mangle(p.Name), e.typ(p.Type, p.Span))
	}
	e.buf.WriteString(")")
	if fn.Result != ir.Void {
		fmt.Fprintf(&e.buf, " %s", e.typ(fn.Result, fn.Span))
	}
	e.buf.WriteString(" {\n")
	e.buf.WriteString(e.paramAccs(fn.Params, "\t"))
	if fn.Async {
		e.asyncBody(fn.Result, fn.Body, 1)
	} else {
		e.body(fn.Body, 1, fn.Result)
	}
	e.buf.WriteString("}\n")
}

func (e *emitter) stmts(stmts []ir.Stmt, depth int) {
	for _, s := range stmts {
		e.stmt(s, depth)
	}
}

func (e *emitter) stmt(s ir.Stmt, depth int) {
	pad := strings.Repeat("\t", depth)
	e.depth = depth
	if e.leaves(s, pad) { // out of a try's literal (emit_try.go)
		return
	}
	if isLoop(s) {
		e.loops++
		defer func() { e.loops-- }()
	}

	switch s := s.(type) {
	case *ir.Throw, *ir.Try:
		e.errorStmt(s, pad, depth)

	case *ir.VarDecl:
		e.varDecl(s, pad) // emit_decl.go

	case *ir.Assign:
		fmt.Fprintf(&e.buf, "%s%s = %s\n", pad, e.top(s.Module, s.Name), e.full(s.Value))

	case *ir.Append:
		fmt.Fprintf(&e.buf, "%s%s\n", pad, e.appendStmt(s))

	case *ir.If:
		fmt.Fprintf(&e.buf, "%sif %s {\n", pad, e.full(s.Cond))
		e.stmts(s.Then, depth+1)
		if len(s.Else) > 0 {
			fmt.Fprintf(&e.buf, "%s} else {\n", pad)
			e.stmts(s.Else, depth+1)
		}
		fmt.Fprintf(&e.buf, "%s}\n", pad)

	case *ir.While:
		fmt.Fprintf(&e.buf, "%sfor %s {\n", pad, e.full(s.Cond))
		e.stmts(s.Body, depth+1)
		fmt.Fprintf(&e.buf, "%s}\n", pad)

	case *ir.For:
		e.forStmt(s, pad, depth)

	case *ir.Break:
		fmt.Fprintf(&e.buf, "%sbreak\n", pad)

	case *ir.Continue:
		fmt.Fprintf(&e.buf, "%scontinue\n", pad)

	case *ir.FieldSet:
		fmt.Fprintf(&e.buf, "%s%s\n", pad, e.fieldSet(s))

	case *ir.FieldDelete:
		fmt.Fprintf(&e.buf, "%s%s\n", pad, e.fieldDelete(s))

	case *ir.IndexSet:
		fmt.Fprintf(&e.buf, "%s%s\n", pad, e.indexSet(s))

	case *ir.ForOf:
		e.forOf(s, pad, depth)

	case *ir.Return:
		switch {
		case s.Value == nil && e.asyncVoid:
			fmt.Fprintf(&e.buf, "%sreturn struct{}{}\n", pad)
		case s.Value == nil:
			fmt.Fprintf(&e.buf, "%sreturn\n", pad)
		default:
			fmt.Fprintf(&e.buf, "%sreturn %s\n", pad, e.full(s.Value))
		}

	case *ir.ExprStmt:
		switch s.Expr.(type) {
		case *ir.Call, *ir.ConsoleLog, *ir.HostCall, *ir.Await, *ir.NewPromise, *ir.ArrayOp, *ir.Cond, *ir.Let:
			fmt.Fprintf(&e.buf, "%s%s\n", pad, e.full(s.Expr))
		default:
			// Go accepts only calls as expression statements, TypeScript any
			// expression: `x => x * 2` in a void slot evaluates and drops.
			fmt.Fprintf(&e.buf, "%s_ = %s\n", pad, e.full(s.Expr))
		}

	default:
		// Recorded rather than skipped: silence would produce a program that
		// builds and quietly does less than the source said.
		e.unsupported = append(e.unsupported, Unsupported{Span: s.StmtSpan(), What: describeUnsupported(s)})
		fmt.Fprintf(&e.buf, "%s#error unhandled statement %T\n", pad, s)
	}
}

func (e *emitter) expr(x ir.Expr) string {
	switch x := x.(type) {
	case *ir.NumberLit:
		if x.Value == 0 && math.Signbit(x.Value) {
			// See runtime.NegZero: this value has no literal spelling in Go.
			e.usesRuntime = true
			return rtPkg + ".NegZero"
		}
		return goFloat(x.Value)

	case *ir.StringLit:
		return strconv.Quote(x.Value)

	case *ir.BoolLit:
		return strconv.FormatBool(x.Value)

	case *ir.NullLit, *ir.UndefinedLit:
		// A bare null or undefined stands for itself, in a log or a
		// comparison, and has no type to be stored as: a maybe's empty
		// states are ir.Empty's. console.log prints one without evaluating
		// it (consoleLog), and `x === null` on a maybe is an ir.IsEmpty, so
		// nothing should reach here.
		return "nil"

	case *ir.Ident:
		return e.read(x)

	case *ir.Binary:
		return e.binary(x)

	case *ir.Unary:
		op, ok := goUnaryOp(x.Op)
		if !ok {
			return e.cannot(x.Span, "the backend cannot emit the operator "+x.Op.String()+" yet")
		}
		return e.unary(op, x)

	case *ir.Convert:
		return e.convert(x)

	case *ir.Call:
		// The callee runs in the caller's domain, which goes first.
		args := []string{e.dom()}
		for _, a := range x.Args {
			args = append(args, e.expr(a))
		}
		return fmt.Sprintf("%s(%s)", e.top(x.Module, x.Callee), strings.Join(args, ", "))

	case *ir.FuncLit:
		return e.funcLit(x)

	case *ir.Await:
		return e.await(x)

	case *ir.NewPromise:
		return e.newPromise(x)

	case *ir.HostCall:
		return e.hostCall(x)

	case *ir.HostProp:
		return e.hostProp(x)

	case *ir.ConsoleLog:
		return e.consoleLog(x)

	case *ir.JSONStringify:
		return e.jsonStringify(x)

	case *ir.BuiltinCall:
		return e.builtinCall(x)

	case *ir.Concat:
		return e.concat(x)

	case *ir.ObjectLit:
		return e.objectLit(x)

	case *ir.FieldGet:
		return e.fieldGet(x)

	case *ir.HasField:
		return e.hasField(x)

	case *ir.ArrayLit:
		return e.arrayLit(x)

	case *ir.IndexGet:
		return e.indexGet(x)

	case *ir.ArrayOp:
		return e.arrayOp(x)

	case *ir.Wrap, *ir.Unwrap, *ir.Empty, *ir.IsEmpty:
		return e.maybe(x)

	case *ir.Cond, *ir.Let:
		return e.cond(x)

	case *ir.Truthy:
		return e.truthy(x)

	case *ir.NewError, *ir.ErrorGet, *ir.Box, *ir.Unbox, *ir.InstanceOf, *ir.TypeOf:
		return e.errorExpr(x) // emit_errors.go

	default:
		e.unsupported = append(e.unsupported, Unsupported{Span: x.ExprSpan(), What: describeUnsupported(x)})
		return fmt.Sprintf("#error unhandled expression %T", x)
	}
}

// funcLit renders a Go function literal. Go closures capture by reference, as
// JavaScript's do, so captured bindings need nothing beyond their names.
func (e *emitter) funcLit(x *ir.FuncLit) string {
	depth := e.depth
	e.usesRuntime = true
	params := []string{domainParam} // its own: the domain of whoever calls it
	for _, p := range x.Params {
		// An empty name is a parameter the literal ignores; mangle gives `_`.
		params = append(params, mangle(p.Name)+" "+e.typ(p.Type, p.Span))
	}
	// The literal's body refers to its own ts_domain parameter, so its uses do
	// not count as the enclosing scope's (main declares one only if it uses it).
	savedVoid, savedDomain := e.asyncVoid, e.usesDomain
	e.asyncVoid = false
	body := e.capture(func() {
		e.buf.WriteString(e.paramAccs(x.Params, strings.Repeat("\t", depth+1)))
		if x.Async {
			e.asyncBody(x.Result, x.Body, depth+1)
		} else {
			e.body(x.Body, depth+1, x.Result)
		}
	})
	e.asyncVoid, e.usesDomain = savedVoid, savedDomain
	e.depth = depth

	result := ""
	if x.Result != ir.Void {
		result = " " + e.typ(x.Result, x.Span)
	}
	return fmt.Sprintf("func(%s)%s {\n%s%s}", strings.Join(params, ", "), result, body, strings.Repeat("\t", depth))
}

func (e *emitter) binary(x *ir.Binary) string {
	if s, ok := e.arith(x); ok {
		return s
	}
	if x.Op == ir.OpAdd && stringish(x.Left.ExprType()) && stringish(x.Right.ExprType()) {
		return e.stringSum(x)
	}
	op, ok := goBinaryOp(x.Op)
	if !ok {
		return e.cannot(x.Span, "the backend cannot emit the operator "+x.Op.String()+" yet")
	}
	if t := x.Left.ExprType(); (x.Op == ir.OpEqual || x.Op == ir.OpNotEqual) && uncomparable(t) {
		return e.cannot(x.Span, "the backend cannot compare a "+t.String()+": Go can't compare functions")
	}
	left, right := e.expr(x.Left), e.expr(x.Right)
	if s, ok := e.stringBinary(x, left, right); ok {
		return s
	}
	// Go evaluates an expression of constants exactly, at compile time, where
	// JavaScript rounds every step as a double: `0.1 + 0.2` would be 0.3,
	// not 0.30000000000000004, and `1e308 * 10` and `0 / 0` compile errors
	// rather than Infinity and NaN, as `i32(i32(2147483647) + i32(1))` would
	// be rather than a wrapped sum. Passing an operand through readFunc makes
	// the operation a run-time one; with one operand a variable, it is one
	// already.
	if arithmetic(x.Op) && x.Typ.IsNumeric() && goConstant(x.Left) && goConstant(x.Right) {
		left = e.runtimeValue(left)
	}
	return unfused(x, fmt.Sprintf("(%s %s %s)", left, op, right))
}

// goFloat renders a TypeScript number as a Go float64 literal.
//
// The suffix matters: Go would treat a bare `5` in a float64 context as an
// untyped constant, which usually works but silently changes meaning in
// division -- `5 / 2` is 2 as integer constants and 2.5 as floats, and
// TypeScript means 2.5.
func goFloat(f float64) string {
	s := strconv.FormatFloat(f, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

// goType spells t as a Go type. ok is false for a type this backend has no
// spelling for, which the caller reports (e.typ) rather than emit a stand-in:
// `any` would build, and quietly lose what the type said.
func goType(t ir.Type) (string, bool) {
	switch t.Kind {
	case ir.KindFunc:
		return goFuncType(t.Sig)
	case ir.KindHost:
		return goHostType(t.Host)
	case ir.KindPromise:
		return goPromiseType(t)
	case ir.KindObject:
		return goObjectType(t.Shape)
	case ir.KindArray:
		return goArrayType(t)
	case ir.KindMaybe:
		return goMaybeType(t)
	case ir.KindUnknown, ir.KindError:
		return goErrorType(t)
	}
	switch t {
	case ir.Number:
		return "float64", true
	case ir.String:
		return "string", true
	case ir.Boolean:
		return "bool", true
	case ir.Int32:
		return "int32", true
	case ir.Int64:
		return "int64", true
	case ir.Uint32:
		return "uint32", true
	case ir.Uint64:
		return "uint64", true
	case ir.Float32:
		return "float32", true
	case ir.Base64:
		// base64 is a compile-time refinement over string, not a distinct
		// runtime representation. See types/cakebear.d.ts.
		return "string", true
	default:
		return "", false
	}
}

// goFuncType spells a function type, which takes the domain first:
// `func(*cakebearrt.Domain, float64, string) bool`. ok is false if any of its
// parameters or its result has no spelling.
func goFuncType(sig *ir.Signature) (string, bool) {
	if sig == nil {
		return "", false
	}
	params := []string{"*" + rtPkg + ".Domain"}
	for _, p := range sig.Params {
		param, ok := goType(p)
		if !ok {
			return "", false
		}
		params = append(params, param)
	}
	s := "func(" + strings.Join(params, ", ") + ")"
	if sig.Result != ir.Void {
		result, ok := goType(sig.Result)
		if !ok {
			return "", false
		}
		s += " " + result
	}
	return s, true
}
