// Writes backend/runtime/width_table.go: the display width Node gives every
// code point, as console.log's array grouping measures it (M4 plan R10).
//
//   node --expose-internals scripts/gen-width-table.mjs | gofmt > backend/runtime/width_table.go
//
// Run it with the Node that cakebear is compared against (the header records
// the version), and rerun it when that changes: the widths are ICU's, and ICU
// follows Unicode.
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { getStringWidth } = require('internal/util/inspect');

const zero = [];
const wide = [];
// A code point NFC decomposes, such as U+1D160, is measured as the code
// points it decomposes into: width 3, say.
const other = [];
const add = (ranges, cp) => {
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1) last[1] = cp;
  else ranges.push([cp, cp]);
};
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue; // a Go string can't hold one
  // false: grouping measures without stripping control characters.
  const w = getStringWidth(String.fromCodePoint(cp), false);
  if (w === 0) add(zero, cp);
  else if (w === 2) add(wide, cp);
  else if (w !== 1) other.push([cp, w]);
}

// Node measures the NFC form of a string, so a pair that composes into a
// character of another width counts as that character. Hangul syllables
// compose by an algorithm (width.go); these are the other pairs whose
// composition changes the width, such as Bengali's two-part vowel signs.
const width = (s) => getStringWidth(s, false);
const pairs = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if ((cp >= 0xd800 && cp <= 0xdfff) || (cp >= 0xac00 && cp <= 0xd7a3)) continue;
  const c = String.fromCodePoint(cp);
  const parts = [...c.normalize('NFD')];
  if (parts.length !== 2 || (parts[0] + parts[1]).normalize('NFC') !== c) continue;
  if (width(c) !== width(parts[0]) + width(parts[1])) {
    pairs.push([parts[0].codePointAt(0), parts[1].codePointAt(0), cp]);
  }
}

const hex = (n) => '0x' + n.toString(16).toUpperCase();
const table = (name, ranges) => {
  const lines = [];
  for (let i = 0; i < ranges.length; i += 4) {
    lines.push('\t' + ranges.slice(i, i + 4).map(([lo, hi]) => `{${hex(lo)}, ${hex(hi)}}`).join(', ') + ',');
  }
  return `var ${name} = []widthRange{\n${lines.join('\n')}\n}\n`;
};

process.stdout.write(`// Code generated by scripts/gen-width-table.mjs. DO NOT EDIT.

// Display widths from Node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}).
// Every code point in none of the tables has width 1.

package runtime

${table('zeroWidth', zero)}
${table('wideWidth', wide)}
// otherWidth holds the code points of any other width, each with its own.
var otherWidth = map[rune]int{
${other.map(([cp, w]) => `\t${hex(cp)}: ${w},`).join('\n')}
}

// composes holds the pairs, other than Hangul's, that NFC composes into a
// character of another width than the two of theirs.
var composes = map[[2]rune]rune{
${pairs.map(([a, b, c]) => `\t{${hex(a)}, ${hex(b)}}: ${hex(c)},`).join('\n')}
}
`);
