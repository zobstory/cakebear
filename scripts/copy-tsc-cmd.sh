#!/usr/bin/env bash
# Copy upstream's cmd/tsc into cmd/cakec, file by file.
#
# cakec is tsc for anything but `cakec build`, and being tsc means running
# cmd/tsc's own code: its System (sys.go), the --lsp and --api servers, and the
# platform files they need. That code is package main, which Go cannot import,
# so cmd/cakec carries a copy of every non-test file except main.go, named
# tsc_<file> under a generated-code header. main.go is mirrored by hand
# instead: cakec's runMain is tsc's plus `build` and cakebear's declarations.
#
# scripts/sync-upstream.sh runs this, so a sync carries upstream's changes to
# these files over before it builds. TestTscCopies (cmd/cakec) fails when a
# copy has drifted from cmd/tsc, and TestTscMainUnchanged when main.go has.
#
# Usage: scripts/copy-tsc-cmd.sh
set -euo pipefail

cd "$(dirname "$0")/.."

# The copies are verbatim but for one line, which gives the language server
# cakebear's declarations: its filesystem goes through lspFS, in
# cmd/cakec/declarations.go (M3 plan D4). If upstream no longer has the line
# exactly once, the script stops rather than drop the change silently. Keep
# all of this in step with tscPatch in cmd/cakec/tsc_copies_test.go.
patch_file=lsp.go
patch_line=$'\tfs := bundled.WrapFS(osvfs.FS())'
patch_with=$'\tfs := lspFS(bundled.WrapFS(osvfs.FS()))'

# Remove the old copies first, so a file upstream deletes loses its copy too.
find cmd/cakec -maxdepth 1 -name 'tsc_*.go' -not -name '*_test.go' -delete

for src in cmd/tsc/*.go; do
  name=$(basename "$src")
  case "$name" in
  main.go | *_test.go) continue ;;
  esac
  dst="cmd/cakec/tsc_$name"
  if [ "$name" != "$patch_file" ]; then
    {
      printf '// Code generated by scripts/copy-tsc-cmd.sh from cmd/tsc/%s. DO NOT EDIT.\n\n' "$name"
      cat "$src"
    } >"$dst"
    continue
  fi
  printf '// Code generated by scripts/copy-tsc-cmd.sh from cmd/tsc/%s, with one line patched. DO NOT EDIT.\n\n' "$name" >"$dst"
  if ! awk -v old="$patch_line" -v new="$patch_with" \
    '$0 == old { print new; n++; next } { print } END { exit n != 1 }' "$src" >>"$dst"; then
    echo "cmd/tsc/$name no longer has, exactly once, the line this script patches:" >&2
    printf '  %s\n' "$patch_line" >&2
    exit 1
  fi
done
