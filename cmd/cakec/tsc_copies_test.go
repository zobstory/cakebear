package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// tscMainSHA256 pins cmd/tsc/main.go, the one file of cmd/tsc that cakec
// mirrors rather than copies: runMain in main.go is its dispatch plus `build`
// and cakebear's declarations.
const tscMainSHA256 = "1ff5702080ef525ef32d97241a17e4f31b8c88c778c6037e577ce976130df7b1"

// tscPatch is the one line scripts/copy-tsc-cmd.sh changes in a copy: the
// language server's filesystem goes through lspFS.
var tscPatch = struct{ file, line, with string }{
	file: "lsp.go",
	line: "\tfs := bundled.WrapFS(osvfs.FS())",
	with: "\tfs := lspFS(bundled.WrapFS(osvfs.FS()))",
}

// tscCopy is what scripts/copy-tsc-cmd.sh writes for cmd/tsc/<name>.
func tscCopy(name string, upstream []byte) ([]byte, error) {
	if name != tscPatch.file {
		header := "// Code generated by scripts/copy-tsc-cmd.sh from cmd/tsc/" + name + ". DO NOT EDIT.\n\n"
		return append([]byte(header), upstream...), nil
	}
	lines := strings.Split(string(upstream), "\n")
	n := 0
	for i, line := range lines {
		if line == tscPatch.line {
			lines[i] = tscPatch.with
			n++
		}
	}
	if n != 1 {
		return nil, fmt.Errorf("cmd/tsc/%s has the line copy-tsc-cmd.sh patches %d times, not once: %q", name, n, tscPatch.line)
	}
	header := "// Code generated by scripts/copy-tsc-cmd.sh from cmd/tsc/" + name + ", with one line patched. DO NOT EDIT.\n\n"
	return []byte(header + strings.Join(lines, "\n")), nil
}

// TestTscCopies holds the tsc_*.go files to cmd/tsc's, byte for byte. They are
// how cakec is tsc (see scripts/copy-tsc-cmd.sh), so a copy that drifts from
// upstream's makes cakec a slightly different tsc, silently. A sync re-copies
// them; this catches a sync that didn't, and a hand edit to a copy.
func TestTscCopies(t *testing.T) {
	t.Parallel()

	upstream, err := filepath.Glob("../tsc/*.go")
	if err != nil {
		t.Fatal(err)
	}
	want := map[string][]byte{}
	for _, path := range upstream {
		name := filepath.Base(path)
		if name == "main.go" || strings.HasSuffix(name, "_test.go") {
			continue
		}
		src, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		copied, err := tscCopy(name, src)
		if err != nil {
			t.Error(err)
			continue
		}
		want["tsc_"+name] = copied
	}
	if _, ok := want["tsc_"+tscPatch.file]; !ok {
		t.Errorf("found no cmd/tsc/%s to patch", tscPatch.file)
	}
	// sys.go is the one every tsc invocation runs; without it this test
	// would pass having compared nothing.
	if _, ok := want["tsc_sys.go"]; !ok {
		t.Fatalf("found no cmd/tsc/sys.go among %q", upstream)
	}

	const fix = "re-copy with scripts/copy-tsc-cmd.sh"
	ours, err := filepath.Glob("tsc_*.go")
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range ours {
		if _, ok := want[name]; !ok && !strings.HasSuffix(name, "_test.go") {
			t.Errorf("%s copies a file cmd/tsc no longer has; %s", name, fix)
		}
	}
	for name, content := range want {
		got, err := os.ReadFile(name)
		switch {
		case err != nil:
			t.Errorf("cmd/tsc/%s has no copy in cmd/cakec; %s", strings.TrimPrefix(name, "tsc_"), fix)
		case !bytes.Equal(got, content):
			t.Errorf("%s differs from cmd/tsc/%s; %s", name, strings.TrimPrefix(name, "tsc_"), fix)
		}
	}
}

// TestTscMainUnchanged fails when upstream changes cmd/tsc/main.go, which
// cakec's runMain mirrors by hand: a new mode there, say, would otherwise
// reach tsc's users and not cakec's.
func TestTscMainUnchanged(t *testing.T) {
	t.Parallel()

	src, err := os.ReadFile("../tsc/main.go")
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(src)
	if got := hex.EncodeToString(sum[:]); got != tscMainSHA256 {
		t.Errorf("cmd/tsc/main.go has changed (sha256 %s): carry the change over to runMain in "+
			"cmd/cakec/main.go, then update tscMainSHA256. The sync commit has the diff: "+
			"git log -p -- cmd/tsc/main.go", got)
	}
}
